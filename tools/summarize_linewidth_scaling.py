"""Render tables and scientific figures from the recorded investigation JSON."""

# Fixed numerical table layout and explicit experiment pass numbers.
# ruff: noqa: PLR2004
from __future__ import annotations

import argparse
import gzip
import json
from pathlib import Path

import matplotlib as mpl

mpl.use("Agg")
import matplotlib.pyplot as plt
import numpy as np


def read_results(path):
    """Expand the lossless archive index without requiring any extra dependencies."""
    payload = json.loads(path.read_text())
    for filename in payload.pop("archives", {}).values():
        payload.update(json.loads(gzip.decompress(path.with_name(filename).read_bytes())))
    return payload


def width_label(run):
    """Show actual starts rather than assume any control is optimal."""
    w = run["widths"]
    return f"{w['F2']:.3f}/{w['F3']:.3f} Hz, {run['scaling']}"


def render_tables(payload, directory):
    """Retain readable target endpoints alongside the complete numerical archive."""
    lines = [
        "# Linewidth/scaling: numerical tables",
        "",
        "Generated by `tools/summarize_linewidth_scaling.py` from "
        "[the numerical records](linewidth-scaling-results.json). "
        "All endpoints below are pass two. χ² uses the actual fitted model.",
        "",
        "## Full-dataset controlled comparison",
        "",
        "| Start F2/F3, scaling | Group | χ² | nfev/njev | Optimality | Shape κ | "
        "Column-scaled J κ | Seconds | Warning |",
        "| --- | ---: | ---: | ---: | ---: | ---: | ---: | ---: | --- |",
    ]
    for run in payload["full_runs"]:
        for g in sorted(run["groups"], key=lambda g: g["cluster_id"]):
            if g["pass"] != 2:
                continue
            lines.append(
                f"| {width_label(run)} | {g['cluster_id']} | {g['chi_squared_actual']:.5f} | "
                f"{g['nfev']}/{g['njev']} | {g['optimality']:.3g} | "
                f"{g['shape_matrix']['condition']:.3g} | "
                f"{g['column_scaled_jacobian']['condition']:.3g} | "
                f"{g['seconds']:.4f} | {'yes' if g['warning'] else 'no'} |"
            )
    lines.extend(
        [
            "",
            "Every row terminated on `ftol`; success does not establish stationarity. "
            "Timing excludes diagnostics. Full records retain status, bounds, "
            "finite-difference checks and every plane amplitude.",
            "",
            "## Position and intrinsic-width endpoints",
            "",
            "Listed positions and first-pass linewidth starts are shown; "
            "the second pass warm-starts from the first. Values are followed by "
            "local standard errors; `—` means unavailable. Neighbor peaks are retained.",
            "",
            "| Start, scaling | Group | Peak | Listed F2/F3 ppm | "
            "Fitted F2 ppm (SE) | Fitted F3 ppm (SE) | "
            "F2 Hz (SE) | F3 Hz (SE) |",
            "| --- | ---: | --- | --- | --- | --- | --- | --- |",
        ]
    )
    selected_runs = [
        payload["full_runs"][0],
        next(
            r
            for r in payload["full_runs"]
            if r["widths"] == payload["representative"] and r["scaling"] == "standard"
        ),
    ]
    for run in selected_runs:
        for g in sorted(run["groups"], key=lambda g: g["cluster_id"]):
            if g["pass"] != 2:
                continue
            first = next(
                r for r in run["groups"] if r["cluster_id"] == g["cluster_id"] and r["pass"] == 1
            )
            for peak in g["peaks"]:
                positions = "/".join(
                    f"{first['parameters'][f'{peak}.{a}.cs']['start']:.6f}" for a in ("F2", "F3")
                )
                values = []
                for axis, label in (("F2", "cs"), ("F3", "cs"), ("F2", "lw"), ("F3", "lw")):
                    p = g["parameters"][f"{peak}.{axis}.{label}"]
                    se = "—" if p["error"] is None else f"{p['error']:.3g}"
                    values.append(f"{p['value']:.7f} ({se})")
                lines.append(
                    f"| {width_label(run)} | {g['cluster_id']} | {peak} | {positions} | "
                    + " | ".join(values)
                    + " |"
                )
    lines.extend(
        [
            "",
            "## Residuals and signed amplitudes",
            "",
            "Amplitudes use the existing acquisition-aware shape normalization; "
            "they are coefficients, not spectral peak heights. Per-plane profiles "
            "and residual RMS are in JSON.",
            "",
            "| Start, scaling | Group | Peak | Amplitude min | Amplitude max | "
            "Mean residual RMS / noise |",
            "| --- | ---: | --- | ---: | ---: | ---: |",
        ]
    )
    for run in selected_runs:
        for g in run["groups"]:
            if g["pass"] != 2:
                continue
            for peak, amps in zip(g["peaks"], g["amplitudes"], strict=True):
                lines.append(
                    f"| {width_label(run)} | {g['cluster_id']} | {peak} | "
                    f"{min(amps):.4g} | {max(amps):.4g} | "
                    f"{np.mean(g['residual_rms_by_plane_in_noise_units']):.3f} |"
                )
    directory.joinpath("linewidth-scaling-tables.md").write_text("\n".join(lines) + "\n")
    return selected_runs


def render_figures(payload, directory, runs):
    """Show intrinsic distributions and complete signed profiles without clipping."""
    selected = [c for c in payload["isolated"]["candidates"] if c["selected"]]
    fig, axes = plt.subplots(1, 2, figsize=(9, 3.5), constrained_layout=True)
    for axis, ax in zip(("F2", "F3"), axes, strict=True):
        values = np.array([c["widths"][axis] for c in selected])
        ax.hist(values, bins=np.arange(5, 22, 1), color="#237a86", alpha=0.8, edgecolor="white")
        ax.axvline(np.median(values), color="#15535b", label=f"Median {np.median(values):.2f} Hz")
        ax.axvline(20, color="#b34433", ls="--", label="Current 20 Hz start")
        ax.axvline(20 / np.pi, color="#6e53a3", ls=":", label="Historical 20/π Hz")
        ax.set(
            title=f"{axis}: intrinsic, unapodized linewidth",
            xlabel="FWHM (Hz)",
            ylabel="Selected resonances",
            xlim=(5, 21),
        )
        ax.legend(fontsize=8)
    fig.savefig(directory / "linewidth-distributions.png", dpi=170)
    plt.close(fig)
    fig, axes = plt.subplots(2, 3, figsize=(12, 6), constrained_layout=True)
    for row, run in enumerate(runs):
        for col, cluster_id in enumerate((269, 360, 424)):
            g = next(g for g in run["groups"] if g["pass"] == 2 and g["cluster_id"] == cluster_id)
            ax = axes[row, col]
            for peak, amps in zip(g["peaks"], g["amplitudes"], strict=True):
                ax.plot(amps, label=peak, lw=1)
            ax.axhline(0, color="black", lw=0.5)
            ax.set(
                title=f"Group {cluster_id}, {'20/20' if row == 0 else '12.06/14.22'} Hz start",
                xlabel="Experimental plane index (all 131)",
                ylabel="Signed amplitude coefficient",
            )
            ax.ticklabel_format(axis="y", style="sci", scilimits=(0, 0))
            ax.legend(fontsize=8)
    fig.savefig(directory / "linewidth-target-profiles.png", dpi=170)
    plt.close(fig)


def main():
    """Regenerate the appendix and figures without rerunning any optimization."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--input",
        type=Path,
        default=Path(__file__).resolve().parents[1]
        / "docs/validation/linewidth-scaling-results.json",
    )
    args = parser.parse_args()
    payload = read_results(args.input)
    runs = render_tables(payload, args.input.parent)
    render_figures(payload, args.input.parent, runs)


if __name__ == "__main__":
    main()
